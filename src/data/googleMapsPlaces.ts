export function searchGoogleMapsPlaces(query: string): GoogleMapsPlaceSuggestion[] {
  const norm = query.toLowerCase().trim();
  if (!norm) return [];

  const matched = ESKISEHIR_MAPS_SUGGESTIONS.filter(
    (item) =>
      item.name.toLowerCase().includes(norm) ||
      item.address.toLowerCase().includes(norm) ||
      item.district.toLowerCase().includes(norm) ||
      item.categoryLabel.toLowerCase().includes(norm)
  );

  // If matched results are fewer than 3, add a dynamic fallback suggestion for the query
  if (matched.length < 5 && norm.length >= 2) {
    const capitalizedQuery = query.charAt(0).toUpperCase() + query.slice(1);
    const dynamicSuggestion: GoogleMapsPlaceSuggestion = {
      id: `gmaps-dyn-${Date.now()}`,
      name: `${capitalizedQuery} (Google Maps Konumu)`,
      category: 'kafe',
      categoryLabel: 'Haritada Kayıtlı Mekân',
      address: `${capitalizedQuery}, Eskişehir`,
      district: 'Tepebaşı',
      city: 'Eskişehir',
      phone: '0222 000 00 00',
      lat: 39.7767 + (Math.random() - 0.5) * 0.015,
      lng: 30.5206 + (Math.random() - 0.5) * 0.015,
      googleMapsUrl: `https://maps.google.com/?q=${encodeURIComponent(query + ' Eskişehir')}`,
      verifiedFromMaps: true,
    };
    return [...matched, dynamicSuggestion];
  }

  return matched;
}
